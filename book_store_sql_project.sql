CREATE DATABASE book_store;
USE book_store;
CREATE TABLE books(
 Book_ID INT PRIMARY KEY,
 Title VARCHAR (100),
 Author VARCHAR (50),
 Genre VARCHAR(50),
 Published_Year INT,
 Price FLOAT,
 Stock INT
 );
-- Data imported from csv file

CREATE TABLE Customers(
 Customer_ID INT PRIMARY KEY,
 Name VARCHAR (50),
 Email VARCHAR (100),
 Phone INT,
 City VARCHAR (100),
 Country VARCHAR (100)
 );
 
-- Data imported from csv file

CREATE TABLE Orders (
    Order_ID INT PRIMARY KEY,
    Customer_ID INT,
    Book_ID INT,
    Order_Date DATE,
    Quantity INT,
    Total_Amount FLOAT,
    FOREIGN KEY (Customer_ID) REFERENCES Customers(Customer_ID),
    FOREIGN KEY (Book_ID) REFERENCES books(Book_ID)
);
